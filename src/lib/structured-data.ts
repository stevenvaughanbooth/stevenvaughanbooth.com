/**
 * schema.org for one case study: an article by Steven, part of the site. The author and the site
 * point at the home page's nodes by @id, and repeat their names so the article stands alone.
 */
export function articleJsonLd(study: CaseStudy) {
  const url = `${site.url}${caseStudyPath(study.id)}`;
  return {
    '@context': 'https://schema.org',
    '@type': 'Article',
    '@id': `${url}#article`,
    headline: study.theme.title,
    description: study.summary,
    url,
    mainEntityOfPage: url,
    image: { '@type': 'ImageObject', url: `${url}/opengraph-image`, ...ogImage },
    datePublished: study.published,
    inLanguage: 'en',
    about: study.theme.kicker,
    author: { '@type': 'Person', '@id': ids.person, name: person.name, url: site.url },
    isPartOf: { '@type': 'WebSite', '@id': ids.website, name: person.name, url: site.url },
  };
}

/**
 * JSON for an inline <script type="application/ld+json">. Escaping '<' keeps any string in the
 * data from closing the script element early.
 */
export function serializeJsonLd(data: unknown): string {
  return JSON.stringify(data).replace(/</g, '\\u003c');
}

